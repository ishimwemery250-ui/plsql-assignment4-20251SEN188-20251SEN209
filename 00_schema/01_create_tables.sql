CREATE TABLE students (
 student_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) PRIMARY KEY,
 full_name VARCHAR2(100) NOT NULL,
 email VARCHAR2(150) NOT NULL UNIQUE,
 status VARCHAR2(12) DEFAULT 'ACTIVE' NOT NULL CHECK (status IN ('ACTIVE','INACTIVE'))
);
CREATE TABLE courses (
 course_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) PRIMARY KEY,
 course_code VARCHAR2(20) NOT NULL UNIQUE,
 title VARCHAR2(100) NOT NULL,
 credits NUMBER(2) NOT NULL CHECK (credits BETWEEN 1 AND 6),
 capacity NUMBER(4) NOT NULL CHECK (capacity BETWEEN 1 AND 500)
);
CREATE TABLE enrollments (
 enrollment_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) PRIMARY KEY,
 student_id NUMBER NOT NULL REFERENCES students(student_id),
 course_id NUMBER NOT NULL REFERENCES courses(course_id),
 enrolled_on DATE DEFAULT SYSDATE NOT NULL,
 grade NUMBER(5,2) CHECK (grade BETWEEN 0 AND 100),
 CONSTRAINT uq_student_course UNIQUE(student_id,course_id)
);
CREATE INDEX idx_enrollments_course ON enrollments(course_id);
